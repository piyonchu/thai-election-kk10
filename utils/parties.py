def party_name(no: int) -> str:
    """Map party ballot number to party name; falls back to a generated label."""
    return PARTY_NAME.get(int(no), f"พรรคหมายเลข {int(no)}")


def party_color(name: str) -> str:
    """Look up canonical color for a party name; grey fallback for unknowns."""
    return PARTY_HEX.get(name, DEFAULT_COLOR)


def color_map(names) -> dict:
    """Build a {party_name: hex} dict for plotly `color_discrete_map`."""
    return {n: party_color(n) for n in names}
